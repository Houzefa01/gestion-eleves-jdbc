package util;

import java.io.File;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

// Gestionnaire de connexion JDBC (Singleton reinitialisable)
public class DBConnection {

    private static DBConnection instance;
    private Connection connection;
    private DatabaseConfig config;
    private boolean tablesInitialized = false;
    private static String currentConfigName;

    private DBConnection(String configName) {
        this.config = new DatabaseConfig(configName);
        currentConfigName = configName;
    }

    public static synchronized void init(String configName) {
        if (instance != null) {
            instance.closeConnection();
        }
        instance = new DBConnection(configName);
        instance.tablesInitialized = false;
    }

    public static String getCurrentDbName() {
        return currentConfigName != null ? currentConfigName : "mariadb";
    }

    public static synchronized DBConnection getInstance() {
        if (instance == null) {
            throw new IllegalStateException("DBConnection.init() n'a pas ete appele. Selectionnez une base de donnees d'abord.");
        }
        return instance;
    }

    public Connection getConnection() throws SQLException {
        if ("access".equals(config.getType())) {
            ensureAccessFile();
        }
        if (connection == null || connection.isClosed()) {
            connection = DriverManager.getConnection(
                    config.getUrl(), config.getUsername(), config.getPassword());
        }
        if (!tablesInitialized) {
            initTables();
            tablesInitialized = true;
        }
        return connection;
    }

    public void closeConnection() {
        if (connection != null) {
            try {
                if (!connection.isClosed()) connection.close();
            } catch (SQLException e) {
                System.err.println("Erreur fermeture connexion : " + e.getMessage());
            }
            connection = null;
        }
    }

    public String getDatabaseType() {
        return config.getType();
    }

    private void initTables() throws SQLException {
        DatabaseMetaData md = connection.getMetaData();
        String type = config.getType();

        if (!tableExists(md, "utilisateurs")) {
            try (Statement stmt = connection.createStatement()) {
                stmt.executeUpdate(createUtilisateursSQL(type));
            }
        }
        if (!tableExists(md, "eleves")) {
            try (Statement stmt = connection.createStatement()) {
                stmt.executeUpdate(createElevesSQL(type));
            }
        }
    }

    private boolean tableExists(DatabaseMetaData md, String tableName) throws SQLException {
        try (ResultSet rs = md.getTables(null, null, tableName, null)) {
            return rs.next();
        }
    }

    private String createUtilisateursSQL(String type) {
        switch (type) {
            case "postgresql":
            case "access":
                return "CREATE TABLE utilisateurs ("
                     + "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "username VARCHAR(50) NOT NULL UNIQUE, "
                     + "password VARCHAR(255) NOT NULL, "
                     + "role VARCHAR(20) NOT NULL DEFAULT 'USER')";
            default:
                return "CREATE TABLE utilisateurs ("
                     + "id INT AUTO_INCREMENT PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "username VARCHAR(50) NOT NULL UNIQUE, "
                     + "password VARCHAR(255) NOT NULL, "
                     + "role VARCHAR(20) NOT NULL DEFAULT 'USER')";
        }
    }

    private String createElevesSQL(String type) {
        switch (type) {
            case "postgresql":
            case "access":
                return "CREATE TABLE eleves ("
                     + "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "prenom VARCHAR(100) NOT NULL, "
                     + "date_naissance DATE NOT NULL, "
                     + "sexe VARCHAR(10) NOT NULL, "
                     + "adresse VARCHAR(255), "
                     + "telephone VARCHAR(20), "
                     + "email VARCHAR(100), "
                     + "classe VARCHAR(50) NOT NULL)";
            default:
                return "CREATE TABLE eleves ("
                     + "id INT AUTO_INCREMENT PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "prenom VARCHAR(100) NOT NULL, "
                     + "date_naissance DATE NOT NULL, "
                     + "sexe VARCHAR(10) NOT NULL, "
                     + "adresse VARCHAR(255), "
                     + "telephone VARCHAR(20), "
                     + "email VARCHAR(100), "
                     + "classe VARCHAR(50) NOT NULL)";
        }
    }

    // Cree ou copie le fichier .accdb s'il n'existe pas
    private void ensureAccessFile() {
        String url = config.getUrl();
        String path = url.replace("jdbc:ucanaccess://", "").replaceAll(";.*", "");
        File target = new File(path);
        if (target.exists()) return;

        // 1. Copier l'exemple depuis le classpath
        try (InputStream in = DBConnection.class.getClassLoader().getResourceAsStream("gestion_eleves_example.accdb")) {
            if (in != null) {
                Path parent = target.getAbsoluteFile().toPath().getParent();
                if (parent != null) Files.createDirectories(parent);
                Files.copy(in, target.toPath());
                System.out.println("Base Access copiee : " + target.getAbsolutePath());
                return;
            }
        } catch (Exception e) {
            System.err.println("Copie exemple impossible : " + e.getMessage());
        }

        // 2. Fallback : creer un .accdb vide
        try {
            Path parent = target.getAbsoluteFile().toPath().getParent();
            if (parent != null) Files.createDirectories(parent);
            java.sql.DriverManager.getConnection(
                "jdbc:ucanaccess://" + target.getAbsolutePath() + ";newDatabaseVersion=V2010").close();
            System.out.println("Base Access vide creee : " + target.getAbsolutePath());
        } catch (Exception e) {
            throw new RuntimeException("Impossible de creer le fichier Access : " + target.getAbsolutePath(), e);
        }
    }
}
