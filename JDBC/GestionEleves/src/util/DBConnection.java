package util;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

// Gestionnaire de connexion JDBC (Singleton)
public class DBConnection {

    private static DBConnection instance;
    private Connection connection;
    private final DatabaseConfig config;
    private boolean tablesInitialized = false;

    private DBConnection() {
        this.config = new DatabaseConfig();
    }

    public static synchronized DBConnection getInstance() {
        if (instance == null) {
            instance = new DBConnection();
        }
        return instance;
    }

    public Connection getConnection() throws SQLException {
        if (connection == null || connection.isClosed()) {
            connection = DriverManager.getConnection(
                    config.getUrl(), config.getUsername(), config.getPassword());
        }
        if (!tablesInitialized) {
            initTables();
            tablesInitialized = true;
        }
        return connection;
    }

    public void closeConnection() {
        if (connection != null) {
            try {
                if (!connection.isClosed()) connection.close();
            } catch (SQLException e) {
                System.err.println("Erreur fermeture connexion : " + e.getMessage());
            }
        }
    }

    public String getDatabaseType() {
        return config.getType();
    }

    private void initTables() throws SQLException {
        DatabaseMetaData md = connection.getMetaData();
        String type = config.getType();

        if (!tableExists(md, "utilisateurs")) {
            try (Statement stmt = connection.createStatement()) {
                stmt.executeUpdate(createUtilisateursSQL(type));
            }
        }
        if (!tableExists(md, "eleves")) {
            try (Statement stmt = connection.createStatement()) {
                stmt.executeUpdate(createElevesSQL(type));
            }
        }
    }

    private boolean tableExists(DatabaseMetaData md, String tableName) throws SQLException {
        try (ResultSet rs = md.getTables(null, null, tableName, null)) {
            return rs.next();
        }
    }

    private String createUtilisateursSQL(String type) {
        switch (type) {
            case "postgresql":
                return "CREATE TABLE utilisateurs ("
                     + "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "username VARCHAR(50) NOT NULL UNIQUE, "
                     + "password VARCHAR(255) NOT NULL, "
                     + "role VARCHAR(20) NOT NULL DEFAULT 'USER')";
            case "access":
                return "CREATE TABLE utilisateurs ("
                     + "id AUTOINCREMENT PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "username VARCHAR(50) NOT NULL UNIQUE, "
                     + "password VARCHAR(255) NOT NULL, "
                     + "role VARCHAR(20) NOT NULL DEFAULT 'USER')";
            default: // mariadb, mysql
                return "CREATE TABLE utilisateurs ("
                     + "id INT AUTO_INCREMENT PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "username VARCHAR(50) NOT NULL UNIQUE, "
                     + "password VARCHAR(255) NOT NULL, "
                     + "role VARCHAR(20) NOT NULL DEFAULT 'USER')";
        }
    }

    private String createElevesSQL(String type) {
        switch (type) {
            case "postgresql":
                return "CREATE TABLE eleves ("
                     + "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "prenom VARCHAR(100) NOT NULL, "
                     + "date_naissance DATE NOT NULL, "
                     + "sexe VARCHAR(10) NOT NULL, "
                     + "adresse VARCHAR(255), "
                     + "telephone VARCHAR(20), "
                     + "email VARCHAR(100), "
                     + "classe VARCHAR(50) NOT NULL)";
            case "access":
                return "CREATE TABLE eleves ("
                     + "id AUTOINCREMENT PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "prenom VARCHAR(100) NOT NULL, "
                     + "date_naissance DATE NOT NULL, "
                     + "sexe VARCHAR(10) NOT NULL, "
                     + "adresse VARCHAR(255), "
                     + "telephone VARCHAR(20), "
                     + "email VARCHAR(100), "
                     + "classe VARCHAR(50) NOT NULL)";
            default: // mariadb, mysql
                return "CREATE TABLE eleves ("
                     + "id INT AUTO_INCREMENT PRIMARY KEY, "
                     + "nom VARCHAR(100) NOT NULL, "
                     + "prenom VARCHAR(100) NOT NULL, "
                     + "date_naissance DATE NOT NULL, "
                     + "sexe VARCHAR(10) NOT NULL, "
                     + "adresse VARCHAR(255), "
                     + "telephone VARCHAR(20), "
                     + "email VARCHAR(100), "
                     + "classe VARCHAR(50) NOT NULL)";
        }
    }
}
